# -*- coding: utf-8 -*-
"""
mflow completion bash|zsh — tab completion of sub-commands and options, generated from the parser.

    mflow completion bash >> ~/.bashrc       # or: eval "$(mflow completion bash)"
    mflow completion zsh  >> ~/.zshrc

File names complete as usual wherever a value is expected.
"""

from __future__ import annotations

import argparse


def _subparsers(parser: argparse.ArgumentParser) -> dict:
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            return dict(action.choices)
    return {}


def _options(parser: argparse.ArgumentParser) -> list[str]:
    return sorted({s for a in parser._actions for s in a.option_strings})


def table() -> dict[str, list[str]]:
    """'' -> top-level words; 'cmd' -> its options (+ sub-commands or positional choices); 'cmd sub' -> options."""
    from .cli import build_parser
    root = build_parser()
    out = {"": sorted(_subparsers(root)) + _options(root)}
    for name, sub in _subparsers(root).items():
        opts = _options(sub)
        nested = _subparsers(sub)
        out[name] = sorted(nested) + opts
        for child, p in nested.items():
            out[f"{name} {child}"] = _options(p)
        for a in sub._actions:                                   # positional choices: validate dimer|eos|…
            if not a.option_strings and a.choices and not isinstance(a, argparse._SubParsersAction):
                out[name] = sorted(a.choices) + opts
                for c in a.choices:
                    out[f"{name} {c}"] = opts
    return out


def bash_script() -> str:
    cases = []
    for key, words in table().items():
        cases.append(f'        "{key}") words="{" ".join(words)}" ;;')
    body = "\n".join(cases)
    return f'''# mflow tab completion (generated by `mflow completion bash`)
_mflow_complete() {{
    local cur="${{COMP_WORDS[COMP_CWORD]}}" prev="${{COMP_WORDS[COMP_CWORD-1]}}" key="" i w words=""
    # a value after an option (-in FILE, -model PATH, …): plain file-name completion
    if [[ "$prev" == -* && "$cur" != -* ]]; then
        COMPREPLY=()
        return
    fi
    for ((i = 1; i < COMP_CWORD; i++)); do
        w="${{COMP_WORDS[i]}}"
        [[ "$w" == -* ]] && break
        key="${{key:+$key }}$w"
    done
    case "$key" in
{body}
        *) words="" ;;
    esac
    if [[ -z "$cur" || "$cur" == -* || ( -n "$words" && "$cur" != */* ) ]]; then
        COMPREPLY=( $(compgen -W "$words" -- "$cur") )
    fi
}}
complete -o default -F _mflow_complete mflow
'''


def cmd_completion(args) -> int:
    script = bash_script()
    if args.shell == "zsh":
        script = "autoload -U +X bashcompinit && bashcompinit\n" + script
    print(script)
    return 0
